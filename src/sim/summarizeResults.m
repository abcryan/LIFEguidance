function summarizeResults(log, p)
%SUMMARIZERESULTS Print convergence and constraint-satisfaction metrics.
t = log.t;
nRho = vecnorm(log.rho, 2, 2);
at = @(x, tq) x(find(t >= tq, 1));
firstBelow = @(x, thr) t(find(x > thr, 1, 'last') + 1);

fprintf('\n=== Closed-loop summary (%g s, Ts = %g s, %d NMPC solves) ===\n', ...
        t(end), p.mpc.Ts, numel(log.mpc));
fprintf('Solver: %d/%d solves succeeded, mean %.2f s, max %.2f s\n', ...
        sum(strcmp({log.mpc.status}, 'Solve_Succeeded')), numel(log.mpc), ...
        mean([log.mpc.solveTime]), max([log.mpc.solveTime]));
fprintf('Attitude error theta: %.1f deg at 0 s, %.2f deg at 200 s, %.3f deg at %g s\n', ...
        rad2deg(log.theta(1)), rad2deg(at(log.theta, 200)), rad2deg(log.theta(end)), t(end));
fprintf('  theta < 1 deg from t = %g s\n', firstBelow(rad2deg(log.theta), 1));
fprintf('Feature point |rho|: %.1f m at 0 s, %.2f m at 600 s, %.4f m at %g s\n', ...
        nRho(1), at(nRho, 600), nRho(end), t(end));
fprintf('  |rho| < 0.1 m from t = %g s; peak rho_z = %.1f m\n', ...
        firstBelow(nRho, 0.1), max(log.rho(:,3)));
fprintf('Peak |w_c/t| = %.4f rad/s (safeguard bound %.2f)\n', ...
        max(vecnorm(log.wct, 2, 2)), p.mpc.wMax);
fprintf('Thrust: max |f_tk| = %.3f N (limit %g), max gimbal-polyhedron residual %.2e N\n', ...
        max(log.fNorm(:)), p.thr.fmax, max(log.gimbalViolation));
fprintf('  max |alpha1|, |alpha3| = %.3f, %.3f rad (pi/4 = %.3f)\n', ...
        max(abs(log.alpha1(:)), [], 'omitnan'), max(abs(log.alpha3(:)), [], 'omitnan'), pi/4);
kIn = find(log.losViolation <= 1e-3, 1);
fprintf('LOS: inside cone from t = %g s; max violation afterwards %.3f m\n', ...
        t(kIn), max(log.losViolation(kIn:end)));
fprintf('Steady state (last 300 s): mean |f_c| = %.3f N, mean |tau_c| = %.3f N m\n', ...
        mean(vecnorm(log.fc(t >= t(end)-300,:), 2, 2)), ...
        mean(vecnorm(log.tauc(t >= t(end)-300,:), 2, 2)));
end
